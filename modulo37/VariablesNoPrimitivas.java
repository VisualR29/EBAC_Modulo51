package com.ebac.modulo37;

public class VariablesNoPrimitivas {

    public static void main(String[] args) {
        byte contador = 127;
        short numerito = 200;
        int edad = 18;
        long numerote = 9999999999999999L;
        float peso = 50.5f;
        double pi = 3.141592653589793;
        boolean activador = false;
        char letra = 'A';

        System.out.println("VARIABLES PRIMITIVAS");
        System.out.println("Byte: " + contador);
        System.out.println("Short: " + numerito);
        System.out.println("Int: " + edad);
        System.out.println("Long: " + numerote);
        System.out.println("Float: " + peso);
        System.out.println("Double: " + pi);
        System.out.println("Boolean: " + activador);
        System.out.println("Char: " + letra);
    }

}
